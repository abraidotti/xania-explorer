"""Shared helpers for level-progression assessments.

Every assessment answers "how balanced is <topic> for a character going from
level 1 to 91 (hero)?", so they share level bands, distribution statistics and
plain-text charts that render in Markdown and diff cleanly in git.
"""

from __future__ import annotations

import csv
import statistics
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

MIN_LEVEL = 1
HERO_LEVEL = 91  # Constants.hpp LEVEL_HERO; 92+ are immortal ranks
LEVELS = range(MIN_LEVEL, HERO_LEVEL + 1)
BAND_WIDTH = 5

GENERATED_NOTE = (
    "<!-- GENERATED by `python -m xania_explorer assess` from xania/area and xania/src. Do not edit by hand. -->\n"
)


@dataclass(frozen=True)
class Band:
    lo: int
    hi: int

    @property
    def label(self) -> str:
        return f"{self.lo}–{self.hi}" if self.lo != self.hi else str(self.lo)

    def __contains__(self, level: int) -> bool:
        return self.lo <= level <= self.hi


def bands(width: int = BAND_WIDTH) -> list[Band]:
    """1–5, 6–10, …, 86–90, 91."""
    return [Band(lo, min(lo + width - 1, HERO_LEVEL)) for lo in range(MIN_LEVEL, HERO_LEVEL + 1, width)]


def cached(world, key: str, factory):
    """Compute an analysis once per loaded world (systems build on each other's analyses)."""
    store = world.__dict__.setdefault("_analysis_cache", {})
    if key not in store:
        store[key] = factory(world)
    return store[key]


def usable_level(level: int) -> int:
    """The character level at which an object/mob of ``level`` becomes relevant
    (level-0 objects are usable from level 1)."""
    return max(MIN_LEVEL, level)


def band_of(level: int, all_bands: Sequence[Band]) -> Band | None:
    return next((b for b in all_bands if level in b), None)


# -- statistics -------------------------------------------------------------
@dataclass(frozen=True)
class Spread:
    """Summary of how evenly a quantity is spread over bins (levels or bands)."""

    total: float
    mean: float
    stdev: float
    cv: float  # coefficient of variation: stdev / mean (0 = perfectly even)
    gini: float  # 0 = perfectly even, 1 = everything in one bin
    min: float
    max: float
    empty_bins: int

    @classmethod
    def of(cls, values: Sequence[float]) -> "Spread":
        vals = list(values)
        total = sum(vals)
        mean = statistics.fmean(vals) if vals else 0.0
        stdev = statistics.pstdev(vals) if len(vals) > 1 else 0.0
        return cls(total, mean, stdev, stdev / mean if mean else 0.0, gini(vals),
                   min(vals, default=0), max(vals, default=0), sum(1 for v in vals if v == 0))

    def describe(self) -> str:
        return (f"total {self.total:g}, mean {self.mean:.1f}/bin, stdev {self.stdev:.1f}, "
                f"CV {self.cv:.2f}, Gini {self.gini:.2f}, range {self.min:g}–{self.max:g}, "
                f"{self.empty_bins} empty bin(s)")


def gini(values: Sequence[float]) -> float:
    vals = sorted(v for v in values if v >= 0)
    n = len(vals)
    total = sum(vals)
    if n == 0 or total == 0:
        return 0.0
    cum = sum((i + 1) * v for i, v in enumerate(vals))
    return (2 * cum) / (n * total) - (n + 1) / n


def median_or(values: Iterable[float], default: float | None = None) -> float | None:
    vals = list(values)
    return statistics.median(vals) if vals else default


def runs_without_increase(series: dict[int, float | None]) -> list[tuple[int, int, float | None]]:
    """Maximal level ranges over which ``series`` doesn't increase.

    Returns (first level, last level, value) for each plateau, longest first.
    ``None`` means "nothing available" and forms its own plateau.
    """
    out = []
    levels = sorted(series)
    start = levels[0]
    for prev, cur in zip(levels, levels[1:]):
        if series[cur] is not None and (series[prev] is None or series[cur] > series[prev]):
            out.append((start, prev, series[prev]))
            start = cur
    out.append((start, levels[-1], series[levels[-1]]))
    return sorted(out, key=lambda r: (-(r[1] - r[0]), r[0]))


# -- rendering --------------------------------------------------------------
def bar(value: float, scale_max: float, width: int = 30) -> str:
    if scale_max <= 0 or value <= 0:
        return ""
    n = value / scale_max * width
    full = int(n)
    return "█" * full + ("▌" if n - full >= 0.5 else "")


def histogram(rows: Sequence[tuple[str, float]], width: int = 40, fmt: str = "{:g}") -> str:
    """A fenced text histogram: one labelled bar per row."""
    if not rows:
        return ""
    label_w = max(len(r[0]) for r in rows)
    top = max(v for _, v in rows) or 1
    lines = [f"{label:>{label_w}} │{bar(v, top, width):<{width}} {fmt.format(v)}" for label, v in rows]
    return "```\n" + "\n".join(lines) + "\n```\n"


def md_cell(value: object) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        value = f"{value:.1f}".rstrip("0").rstrip(".")
    return str(value).replace("\n", " ").replace("|", "\\|")


def table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(md_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def write_csv(path: Path, headers: Sequence[str], rows: Iterable[Sequence[object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(headers)
        w.writerows(rows)
